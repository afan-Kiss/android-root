# -*- encoding: utf-8 -*-
"""Pure-Python X-Ladon generator for Douyin v39."""

import base64
import os
def gen_ladon_v39(raw=None):
    """Encode a captured v39 X-Ladon payload.

    Offline executions of MSSDK VMP program 0x456 with identical request and
    timestamp produce a different four-byte value on every invocation. The
    value is therefore the per-request nonce generated by the program, not a
    deterministic digest of the URL.
    """
    raw = os.urandom(4) if raw is None else bytes(raw)
    if len(raw) != 4:
        raise ValueError("X-Ladon payload must contain exactly four bytes")
    return base64.b64encode(raw).decode()


def encrypt_ladon(url=None, headers=None, khronos=0, raw=None):
    """Generate the request nonce; URL fields do not bind v39 X-Ladon."""
    return gen_ladon_v39(raw)


